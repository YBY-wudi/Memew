/* ============ 提示词 2：AI 趣味类比 + 典故 + 记忆技巧 ============ */
/*
 类比记忆的质量红线（小程序的特色功能，必须做硬）
 ------------------------------------------------------------------
 之前这四条要求太笼统，AI 经常给出「都很重要」这种无效比喻。
 现在加了可检验的判定标准：

 ① 必须写清「X 对应 Y」的逐条映射，不能只说共同点
 ② 必须指出「这个类比在哪失效」——只讲好处的类比是危险的
 ③ 必须体现知识点的**可对比结构**（两个相反/并列的现象）
    例：高温变性不可逆 vs 低温只降活性可恢复
 ④ 例举要具体到生活细节，不能停留在概念层
    反例：「像加热会破坏蛋白质」→ 太浅
    正例：「煮鸡蛋，蛋白凝固后晾凉也不会变回液态」
*/
const ANALOGY_RULE =
  '\n【类比质量硬性要求（逐条自检，不满足就重写）】\n' +
  '1. 结构对应：必须写出「知识点要素A ↔ 类比物要素B」的逐条映射，' +
  '不能只说「它们很像 / 都很重要」；\n' +
  '2. 对比结构：如果知识点里有两个相反或并列的现象（如高温与低温、' +
  '有性与无性、逆流与顺流），类比必须把两个都覆盖，形成对照；\n' +
  '3. 生活细节：例举要具体到动作和现象（煮鸡蛋、腌咸菜、吹气球），' +
  '不能停留在「加热」「改变」这类抽象词；\n' +
  '4. 失效点：最后必须写明「这个类比在哪不适用」，避免把类比当结论；\n' +
  '5. 若知识点本身没有可类比的结构，就如实说「本条结构特殊，' +
  '不适合类比」，不要硬凑。';

