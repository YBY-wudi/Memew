/* ============ 关联类型表（知识组网的核心）============
 *
 * 🔴 为什么单独抽成常量，而不是只写在提示词字符串里：
 *   关联类型是**产品概念**，不只是提示词的一部分 ——
 *   前端要用它上色（不同关系给不同颜色）、决定图标、在组网页分组显示。
 *   如果只存在于提示词里，前端就得另外写死一份，
 *   于是两处必然对不上（加了一个类型，忘了同步前端）。
 *
 *   教学上「关联记忆」之所以有效，是因为它**双向可提示**：
 *     A 记住了 → 顺着关系能提示出 B
 *     B 记住了 → 反向也能提示回 A
 *   所以每种关联都要能双向描述。这是这个功能的灵魂，
 *   下面每条的 reverse 字段就是给用户看的「怎么提示」。
 *
 *   kind    机器标识，前端上色/图标用
 *   label   给用户看的中文名
 *   color   渐变色 key（对应 styles/gradients.wxss）
 *   cue     给 AI 的判定依据 —— 写清楚才不会乱标
 *   reverse 反向提示语
 */
